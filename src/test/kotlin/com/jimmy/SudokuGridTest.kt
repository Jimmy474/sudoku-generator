package com.jimmy

import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertTrue

class SudokuGridTest {

    private val gridString = "379284615428561739561793428213657984786149253945328176157436892692875341834912567"

    @Test
    fun `test cell removal across all versions`() {
        val versionFactories = listOf(
            ::V1SudokuGridBase,
            ::V2SudokuGridPacked,
            ::V3SudokuGridFilteredSelection,
            ::V4SudokuGridCaching,
            ::V5SudokuGridLimitedSolutions,
            ::V6SudokuGridBetterRandomSelection,
        )

        val generator = GridGenerator(12345L)

        for (factory in versionFactories) {
            val grid = factory()
            generator.generateRandom(grid, gridString)
            assertEquals(81, grid.nonEmptyCount())
            assertTrue(grid.isValid())

            val removed = grid.playable(25)
            assertTrue(removed <= 25, "Version ${grid.v} should remove at most 25 cells")
            assertEquals(81 - removed, grid.nonEmptyCount())
            assertEquals(1, grid.solveCount(), "Grid generated by version ${grid.v} must have a unique solution")
        }
    }

    @Test
    fun `test cell removal with moderate difficulty`() {
        val generator = GridGenerator(42L)
        val grid = V1SudokuGridBase()
        generator.generateRandom(grid, gridString)

        val target = 20
        val removed = grid.playable(target)
        assertTrue(removed in 1..target)
        assertEquals(81 - removed, grid.nonEmptyCount())
        assertEquals(1, grid.solveCount())
    }
}
